import csv
import os
import time
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors

class ReportGenerator:
    def __init__(self, output_dir="reports"):
        self.output_dir = output_dir
        self.logs = []
        self.start_time = time.time()
        
        if not os.path.exists(self.output_dir):
            os.makedirs(self.output_dir)

    def log_data(self, attention, fatigue, status):
        timestamp = datetime.now().strftime("%H:%M:%S")
        self.logs.append({
            "Timestamp": timestamp,
            "Attention": round(attention, 3),
            "Fatigue": round(fatigue, 3),
            "Status": status
        })

    def generate_report(self):
        if not self.logs:
            print("No data logged. Skipping report generation.")
            return None, None, None

        timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
        csv_path = os.path.join(self.output_dir, f"session_data_{timestamp_str}.csv")
        txt_path = os.path.join(self.output_dir, f"summary_{timestamp_str}.txt")
        pdf_path = os.path.join(self.output_dir, f"report_{timestamp_str}.pdf")

        # 1. Save CSV
        keys = self.logs[0].keys()
        with open(csv_path, 'w', newline='') as f:
            dict_writer = csv.DictWriter(f, fieldnames=keys)
            dict_writer.writeheader()
            dict_writer.writerows(self.logs)

        # 2. Calculate Statistics
        total_logs = len(self.logs)
        avg_attn = sum(l['Attention'] for l in self.logs) / total_logs
        avg_fatg = sum(l['Fatigue'] for l in self.logs) / total_logs
        
        status_counts = {}
        for l in self.logs:
            s = l['Status']
            status_counts[s] = status_counts.get(s, 0) + 1
            
        peak_fatigue_entry = max(self.logs, key=lambda x: x['Fatigue'])
        
        duration = time.time() - self.start_time
        minutes = int(duration // 60)
        seconds = int(duration % 60)

        # 3. Save Text Summary (Legacy support)
        with open(txt_path, 'w') as f:
            f.write(f"Session Summary - {datetime.now().strftime('%Y-%m-%d')}\n")
            f.write(f"Duration: {minutes}m {seconds}s\n")
            f.write(f"Avg Attention: {avg_attn*100:.1f}%\n")
            f.write(f"Avg Fatigue: {avg_fatg*100:.1f}%\n")

        # 4. Generate Professional PDF Report
        try:
            c = canvas.Canvas(pdf_path, pagesize=letter)
            width, height = letter

            # Header Background
            c.setFillColorRGB(0.1, 0.1, 0.1)
            c.rect(0, height-100, width, 100, fill=1)

            # Title
            c.setFillColor(colors.white)
            c.setFont("Helvetica-Bold", 24)
            c.drawString(50, height-60, "ATTENTION & FATIGUE REPORT")
            
            c.setFont("Helvetica", 12)
            c.drawString(50, height-85, f"Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")

            # Session Info
            c.setFillColor(colors.black)
            c.setFont("Helvetica-Bold", 16)
            c.drawString(50, height-150, "Session Metrics")
            c.line(50, height-155, 200, height-155)

            c.setFont("Helvetica", 12)
            metrics = [
                f"Total Session Duration: {minutes} minutes {seconds} seconds",
                f"Average Attention Score: {avg_attn*100:.1f}%",
                f"Average Fatigue Index: {avg_fatg*100:.1f}%",
                f"Peak Fatigue Detected at: {peak_fatigue_entry['Timestamp']} ({peak_fatigue_entry['Fatigue']*100:.1f}%)"
            ]
            for i, text in enumerate(metrics):
                c.drawString(70, height-180 - (i*25), text)

            # Status Summary
            c.setFont("Helvetica-Bold", 16)
            c.drawString(50, height-300, "User State Distribution")
            c.line(50, height-305, 230, height-305)

            c.setFont("Helvetica", 12)
            y_pos = height-330
            for status, count in status_counts.items():
                percentage = (count / total_logs) * 100
                # Choose color based on status
                if status == "ATTENTIVE": c.setFillColor(colors.darkgreen)
                elif status == "FATIGUED": c.setFillColor(colors.red)
                else: c.setFillColor(colors.orange)
                
                c.drawString(70, y_pos, f"• {status}: {percentage:.1f}% of total session time")
                y_pos -= 25

            # Footer
            c.setFillColor(colors.grey)
            c.setFont("Helvetica-Oblique", 10)
            c.drawCentredString(width/2, 50, "This report was automatically generated by the Multimodal AI Attention Monitor.")

            c.save()
        except Exception as e:
            print(f"Error generating PDF: {e}")
            pdf_path = None

        return csv_path, txt_path, pdf_path
